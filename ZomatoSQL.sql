--Revenue & Sales Analysis
--1)What is the total revenue generated by the platform?
SELECT SUM(final_amount) AS Total_revenue 
FROM orders;

--2)How has revenue changed month-over-month?
WITH monthly_revenue AS (
    SELECT 
        DATE_TRUNC('month', order_date) AS month,
        SUM(order_amount) AS Revenue
    FROM orders
    GROUP BY 1
)
SELECT
    month,
    Revenue,
    LAG(Revenue) OVER (ORDER BY month) AS pre_revenue,
    Revenue - LAG(Revenue) OVER (ORDER BY month) AS revenue_change,
    ROUND(
        (
            (Revenue - LAG(Revenue) OVER (ORDER BY month))
            / NULLIF(LAG(Revenue) OVER (ORDER BY month), 0) * 100
        )::numeric,
        2
    ) AS pct_change
FROM monthly_revenue
ORDER BY month;

--3)Which cities generate the highest revenue?
SELECT r.city,SUM(order_amount) AS total_revenue
FROM orders o
JOIN restaurants r ON o.restaurant_id=r.restaurant_id
GROUP BY r.city
ORDER BY total_revenue DESC
LIMIT 5;

--4)Which restaurants generate the most revenue?
SELECT r.restaurant_name,SUM(order_amount) AS most_revenue
FROM orders o
JOIN restaurants r ON o.restaurant_id=r.restaurant_id
GROUP BY r.restaurant_name
ORDER BY most_revenue DESC
LIMIT 5;

--5)Which cuisines generate the highest revenue?
SELECT r.cuisine_type,SUM(order_amount) AS highest_revenue
FROM orders o
JOIN restaurants r ON o.restaurant_id=r.restaurant_id
GROUP BY r.cuisine_type 
ORDER BY highest_revenue
LIMIT 1;

--Customer Analysis
--6)Who are the top 10 customers by total spending?
SELECT c.customer_name,SUM(order_amount) AS Total_spendings
FROM orders o
JOIN customers c ON o.customer_id=c.customer_id 
GROUP BY c.customer_name
ORDER BY Total_spendings DESC
LIMIT 10;

--7)Which customers have placed the highest number of orders?
SELECT c.customer_id,c.customer_name,COUNT(*) AS highest_orders
FROM orders o
JOIN customers c ON o.customer_id=c.customer_id
GROUP BY c.customer_id
ORDER BY highest_orders DESC
LIMIT 5;

--8)What is the average spending per customer?
SELECT AVG(total_spent) AS average_spending
FROM(
	SELECT customer_id,SUM(order_amount) AS total_spent
	FROM orders
	GROUP BY customer_id
)AS customer_totals; 

--9)What percentage of customers are repeat customers?
SELECT c.customer_name,c.customer_id,COUNT(order_id)
FROM customers c
JOIN orders o ON c.customer_id=o.customer_id
GROUP BY c.customer_id
HAVING COUNT(c.customer_id)>1;

