--Business Value: Measures restaurant popularity.
--13)Which restaurants have high ratings but low sales?
SELECT r.restaurant_id,r.restaurant_name,MAX(r.rating) AS high_rating,SUM(o.order_amount) AS less_sales
FROM restaurants r
JOIN orders o ON r.restaurant_id=o.restaurant_id
GROUP BY r.restaurant_id,r.restaurant_name
HAVING  MAX(r.rating)>4.5 
ORDER BY high_rating DESC,less_sales ASC;

--14)Rank restaurants by revenue within each city.
WITH restaurant_revenue AS(
	SELECT r.restaurant_id,r.restaurant_name,r.city,SUM(o.order_amount) AS revenue
	FROM restaurants r
	JOIN orders o ON r.restaurant_id=o.restaurant_id
	GROUP BY r.city,r.restaurant_id,r.restaurant_name
)
SELECT city,restaurant_name,revenue,
	DENSE_RANK() OVER(PARTITION BY city ORDER BY revenue DESC) AS revenue_rank
FROM restaurant_revenue;

--15)Which day of the week receives the most orders?
SELECT TRIM(TO_CHAR(order_date,'Day')) AS day_name,COUNT(*) AS orders
FROM orders
GROUP BY TRIM(TO_CHAR(order_date,'Day'))
ORDER BY orders DESC
LIMIT 1;

--16)Which hour of the day receives the most orders?
SELECT EXTRACT(HOUR FROM order_date) AS hour_in_day,COUNT(*) AS orders
FROM orders
GROUP BY EXTRACT(HOUR FROM order_date)
ORDER BY orders DESC
LIMIT 1;

--17)What is the cancellation rate by restaurant?
SELECT r.restaurant_id, r.restaurant_name,
       ROUND(100.0 * SUM(CASE WHEN o.order_status='Cancelled' THEN 1 ELSE 0 END)/ COUNT(*),2) AS cancellation_rate
FROM orders o
JOIN restaurants r
ON o.restaurant_id = r.restaurant_id
GROUP BY r.restaurant_id, r.restaurant_name;

--18)Find restaurants that have never received an order.
SELECT r.restaurant_id, r.restaurant_name
FROM restaurants r
LEFT JOIN orders o ON r.restaurant_id = o.restaurant_id
WHERE o.order_id IS NULL;
