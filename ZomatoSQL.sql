--creating a Restaurants table
DROP TABLE IF EXISTS restaurants;
CREATE TABLE restaurants (
    restaurant_id VARCHAR(10) PRIMARY KEY,
    restaurant_name VARCHAR(150),
    city VARCHAR(50),
    cuisine_type VARCHAR(50),
    avg_cost_for_two INT,
    rating DECIMAL(3,1), 
    total_votes INT,
    delivery_time_mins INT,
    is_veg_only VARCHAR(3),
    has_online_delivery VARCHAR(3),
    opened_year INT
);

--Creating orders table
DROP TABLE IF EXISTS orders;
CREATE TABLE orders (
    order_id VARCHAR(10) PRIMARY KEY,
    customer_id VARCHAR(10) NOT NULL,
    restaurant_id VARCHAR(10) NOT NULL,
    order_date TIMESTAMP NOT NULL,
    items_ordered VARCHAR(1000),
    quantity INT,
    order_amount DECIMAL(10,2),
    delivery_charge DECIMAL(10,2),
    discount_applied DECIMAL(10,2),
    final_amount DECIMAL(10,2),
    payment_method VARCHAR(30),
    order_status VARCHAR(20),
    delivery_time_mins INT,
	customer_rating INT,
    delivery_partner_id VARCHAR(10),

    FOREIGN KEY (customer_id) REFERENCES customers(customer_id),
    FOREIGN KEY (restaurant_id) REFERENCES restaurants(restaurant_id)
);
--Creating customers table
DROP TABLE IF EXISTS customers;
CREATE TABLE customers (
    customer_id VARCHAR(10) PRIMARY KEY,
    customer_name VARCHAR(100) NOT NULL,
    city VARCHAR(50),
    age INT,
    gender VARCHAR(10),
    registered_date DATE,
    total_orders INT,
    zomato_gold VARCHAR(3),
    preferred_cuisine VARCHAR(50),
    avg_rating_given DECIMAL(2,1)
);

